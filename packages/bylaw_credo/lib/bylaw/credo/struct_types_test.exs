defmodule Bylaw.Credo.StructTypesTest do
  use ExUnit.Case, async: true

  alias Bylaw.Credo.StructTypes

  alias __MODULE__.Aliased
  alias __MODULE__.CompleteException
  alias __MODULE__.Empty
  alias __MODULE__.Full
  alias __MODULE__.GeneratedFull
  alias __MODULE__.GeneratedPartial
  alias __MODULE__.Grouped
  alias __MODULE__.Missing
  alias __MODULE__.Nested
  alias __MODULE__.Opaque
  alias __MODULE__.Parameterized
  alias __MODULE__.Partial
  alias __MODULE__.Private
  alias __MODULE__.TypeAlias
  alias __MODULE__.Union

  defp validate(modules), do: StructTypes.validate(modules, [__ENV__.file])

  test "rejects empty and partially specified types despite compiler-added fields" do
    assert {:error, issues} = validate([Empty, Partial])
    assert Enum.map(issues, & &1.missing_fields) == [[:a, :b], [:b]]
    assert Enum.all?(issues, &(&1.reason == :fields_missing))
  end

  test "requires a public zero-arity t type for every owned struct" do
    assert {:error, issues} = validate([Missing, Private, Parameterized])
    assert Enum.all?(issues, &(&1.reason == :type_missing))
    assert Enum.count(issues) == 3
  end

  test "accepts complete opaque types and explicit term types" do
    assert :ok = validate([Full, Opaque])
  end

  test "checks fields generated by schema-like macros and exceptions" do
    assert :ok = validate([GeneratedFull, CompleteException])
    assert {:error, [issue]} = validate([GeneratedPartial])
    assert issue.missing_fields == [:__meta__, :id, :inserted_at, :parent, :parent_id]
  end

  test "resolves aliases and isolates nested module declarations" do
    assert :ok = validate([Aliased, Grouped, Nested, Nested.Inner])
    assert {:error, [issue]} = validate([Nested.Missing])
    assert issue.reason == :type_missing
  end

  test "rejects a partial struct branch alongside a complete branch" do
    assert {:error, [issue]} = validate([Union])
    assert issue.missing_fields == [:b]
  end

  test "reports unsupported aliases and missing source or modules clearly" do
    assert {:error, [issue]} = validate([TypeAlias])
    assert issue.reason == :type_unverifiable
    assert {:error, [issue]} = StructTypes.validate([Full], [])
    assert issue.reason == :source_missing
    assert {:error, [issue]} = validate([NotARealModule])
    assert issue.reason == :module_unavailable
    assert {:error, [issue]} = StructTypes.validate([], ["/not/a/real/source.ex"])
    assert issue.reason == :source_unavailable
  end

  test "does not require struct types for modules without structs" do
    assert :ok = validate([__MODULE__, Enum])
  end

  defmodule Empty do
    defstruct [:a, :b]
    # This intentionally incomplete fixture proves the audit catches compiler-filled fields.
    # credo:disable-for-next-line Bylaw.Credo.Check.Elixir.FullySpecifiedStructTypes
    @type t :: %__MODULE__{}
  end

  defmodule Partial do
    defstruct [:a, :b]
    @type t :: %__MODULE__{a: integer()}
  end

  defmodule Missing do
    defstruct [:a]
  end

  defmodule Private do
    defstruct [:a]
    @typep t :: %__MODULE__{a: term()}
    @spec identity(t()) :: t()
    def identity(value), do: value
  end

  defmodule Parameterized do
    defstruct [:a]
    @type t(value) :: %__MODULE__{a: value}
  end

  defmodule Full do
    defstruct [:a, :b]
    @type t :: %__MODULE__{a: integer(), b: term()}
  end

  defmodule Opaque do
    defstruct [:a]
    @opaque t :: %__MODULE__{a: term()}
  end

  defmodule SchemaLike do
    defmacro __using__(_options) do
      quote do
        defstruct [:__meta__, :id, :inserted_at, :parent, :parent_id, :name]
      end
    end
  end

  defmodule GeneratedFull do
    use SchemaLike

    @type t :: %__MODULE__{
            __meta__: term(),
            id: term(),
            inserted_at: term(),
            parent: term(),
            parent_id: term(),
            name: term()
          }
  end

  defmodule GeneratedPartial do
    use SchemaLike
    @type t :: %__MODULE__{name: String.t()}
  end

  defmodule CompleteException do
    defexception [:message]
    @type t :: %__MODULE__{__exception__: true, message: String.t() | nil}
  end

  defmodule Aliased do
    # This fixture exercises aliases rather than prescribing an application alias style.
    # credo:disable-for-next-line Credo.Check.Readability.AliasAs
    alias __MODULE__, as: Self
    defstruct [:a]
    @type t :: %Self{a: term()}
  end

  defmodule Grouped do
    # This fixture verifies parsing of grouped alias syntax.
    # credo:disable-for-next-line /MultiAlias|UnnecessaryAliasExpansion/
    alias Elixir.Bylaw.Credo.StructTypesTest.{Grouped}
    defstruct [:a]
    @type t :: %Grouped{a: term()}
  end

  defmodule Nested do
    defstruct [:outer]
    @type t :: %__MODULE__{outer: term()}

    defmodule Inner do
      defstruct [:inner]
      @type t :: %__MODULE__{inner: term()}
    end

    defmodule Missing do
      defstruct [:inner]
    end
  end

  defmodule Union do
    defstruct [:a, :b]
    @type t :: %__MODULE__{a: integer(), b: term()} | %__MODULE__{a: integer()}
  end

  defmodule TypeAlias do
    defstruct [:a]
    @type own :: %__MODULE__{a: term()}
    @type t :: own()
  end
end
