defmodule Bylaw.Credo.StructTypes do
  @moduledoc """
  Checks explicit source declarations against compiled structs.

  Pass all modules owned by the application and their source file paths after
  compilation. Every struct must declare a public `@type t/0` or `@opaque t/0`
  whose own-struct branches explicitly list every compiled field. This includes
  fields introduced by macros, associations, metadata and exceptions.

  Sources are parsed, never evaluated. Type aliases and generated declarations
  that cannot be verified from source produce an error rather than an exemption.
  Compiled types alone cannot establish completeness: Elixir inserts `term()`
  for omitted struct fields.

      modules = Application.spec(:my_app, :modules)
      sources = Path.wildcard("lib/**/*.ex")
      :ok = Bylaw.Credo.StructTypes.validate(modules, sources)
  """

  alias Bylaw.Credo.SourceTypes
  alias Bylaw.Credo.UUIDSchema

  @type issue :: %{
          module: module() | nil,
          file: String.t() | nil,
          line: pos_integer() | nil,
          reason: atom(),
          missing_fields: list(atom()),
          message: String.t()
        }

  @doc "Validates every compiled struct in `modules` against its source declaration."
  @spec validate(list(module()), list(String.t())) :: :ok | {:error, list(issue())}
  def validate(modules, source_files), do: validate(modules, source_files, [])

  @doc """
  Validates struct declarations and optional compiled Ecto UUID conventions.

  Options (all disabled by default): `:uuid_fields` requires `Ecto.UUID.t()`
  for actual `:binary_id` and `Ecto.UUID` fields; `:uuid_primary_keys` requires
  nonempty, exclusively UUID primary keys on persisted schemas; `:uuid_version` requires every
  autogenerated UUID primary key to use native Ecto.UUID generation with the
  given version (4 or 7). Nongenerated shared primary keys are allowed. Identity conventions do not apply
  to embedded schemas.

  Sources remain mandatory. Custom macros are resolved through compiled schema
  metadata, never evaluated from source. Custom UUID types are not inferred.
  """
  @spec validate(list(module()), list(String.t()), keyword()) :: :ok | {:error, list(issue())}
  def validate(modules, source_files, opts) when is_list(modules) and is_list(source_files) do
    validate_options!(opts)
    {index, source_issues} = SourceTypes.index(source_files)

    module_issues =
      modules
      |> Enum.uniq()
      |> Enum.flat_map(&(validate_module(&1, index) ++ validate_schema(&1, index, opts)))

    issues = source_issues ++ module_issues

    if Enum.empty?(issues) do
      :ok
    else
      {:error, issues}
    end
  end

  defp validate_module(module, index) do
    case Code.ensure_loaded(module) do
      {:module, ^module} ->
        if function_exported?(module, :__struct__, 0) do
          validate_struct(module, index)
        else
          []
        end

      {:error, reason} ->
        [
          issue(
            module,
            nil,
            nil,
            :module_unavailable,
            [],
            "Cannot load module: #{inspect(reason)}"
          )
        ]
    end
  end

  defp validate_struct(module, index) do
    fields =
      module.__struct__()
      |> Map.keys()
      |> List.delete(:__struct__)
      |> Enum.sort()

    case Map.fetch(index, module) do
      :error ->
        [
          issue(
            module,
            nil,
            nil,
            :source_missing,
            fields,
            "No source declaration found for compiled struct"
          )
        ]

      {:ok, entry} ->
        types = Enum.filter(entry.types, &(&1.kind in [:type, :opaque]))

        if Enum.empty?(types) do
          [
            issue(
              module,
              entry.file,
              entry.line,
              :type_missing,
              fields,
              "Declare a public @type or @opaque t/0 with every struct field"
            )
          ]
        else
          Enum.flat_map(types, &validate_type(&1, module, fields, entry.file))
        end
    end
  end

  defp validate_type(type, module, fields, file) do
    case SourceTypes.struct_branches(type.body, module, type.aliases) do
      {:ok, branches} ->
        Enum.flat_map(
          branches,
          &missing_field_issues(fields -- Keyword.keys(&1), module, file, type.line)
        )

      :unsupported ->
        [
          issue(
            module,
            file,
            type.line,
            :type_unverifiable,
            [],
            "Cannot verify t/0; declare explicit own-struct field types in each branch"
          )
        ]
    end
  end

  defp missing_field_issues([], _module, _file, _line), do: []

  defp missing_field_issues(missing, module, file, line) do
    [
      issue(
        module,
        file,
        line,
        :fields_missing,
        missing,
        "Explicitly type missing struct fields: #{inspect(missing)}"
      )
    ]
  end

  defp validate_options!(opts) do
    unless Keyword.keyword?(opts) and
             Enum.all?(opts, fn
               {key, value} when key in [:uuid_fields, :uuid_primary_keys] -> is_boolean(value)
               {:uuid_version, version} -> version in [4, 7]
               _other -> false
             end) do
      raise ArgumentError,
            "expected UUID options: uuid_fields: boolean, uuid_primary_keys: boolean, uuid_version: 4 | 7"
    end
  end

  defp validate_schema(module, index, opts) do
    enabled =
      Keyword.get(opts, :uuid_fields, false) or
        Keyword.get(opts, :uuid_primary_keys, false) or Keyword.has_key?(opts, :uuid_version)

    if enabled and function_exported?(module, :__schema__, 1) do
      case Map.fetch(index, module) do
        {:ok, entry} ->
          uuid_field_issues(module, entry, opts) ++ identity_issues(module, entry, opts)

        :error ->
          []
      end
    else
      []
    end
  end

  defp uuid_field_issues(module, entry, opts) do
    if Keyword.get(opts, :uuid_fields, false) do
      fields =
        module
        |> uuid_fields()
        |> Enum.sort()

      entry
      |> UUIDSchema.invalid_fields(module, fields)
      |> Enum.map(fn {line, invalid} ->
        issue(
          module,
          entry.file,
          line,
          :uuid_field_type,
          invalid,
          "Type UUID fields explicitly as Ecto.UUID.t() or Ecto.UUID.t() | nil: #{inspect(invalid)}"
        )
      end)
    else
      []
    end
  end

  defp identity_issues(module, entry, opts) do
    if module.__schema__(:source) == nil do
      []
    else
      primary_key_issues(module, entry, opts) ++ generation_issues(module, entry, opts)
    end
  end

  defp primary_key_issues(module, entry, opts) do
    keys = module.__schema__(:primary_key)

    if Keyword.get(opts, :uuid_primary_keys, false) and
         (Enum.empty?(keys) or
            Enum.any?(keys, &(not UUIDSchema.uuid_type?(module.__schema__(:type, &1))))) do
      [
        issue(
          module,
          entry.file,
          entry.line,
          :uuid_primary_key,
          keys,
          "Declare a nonempty primary key using only :binary_id or Ecto.UUID fields"
        )
      ]
    else
      []
    end
  end

  defp generation_issues(module, entry, opts) do
    case Keyword.fetch(opts, :uuid_version) do
      {:ok, version} ->
        keys = module.__schema__(:primary_key)
        adapter = module.__schema__(:autogenerate_id)
        generated = module.__schema__(:autogenerate)

        invalid = Enum.filter(keys, &invalid_generation?(module, &1, adapter, generated, version))

        if Enum.empty?(invalid) do
          []
        else
          [
            issue(
              module,
              entry.file,
              entry.line,
              :uuid_generation,
              invalid,
              "Autogenerated UUID primary keys must explicitly use Ecto.UUID with version #{version}"
            )
          ]
        end

      :error ->
        []
    end
  end

  defp uuid_fields(module) do
    fields = module.__schema__(:fields)
    virtual_fields = module.__schema__(:virtual_fields)
    persisted = Enum.filter(fields, &uuid_field?(module, &1))

    virtual =
      Enum.filter(virtual_fields, fn field ->
        type = module.__schema__(:virtual_type, field)
        UUIDSchema.uuid_type?(type)
      end)

    persisted ++ virtual
  end

  defp uuid_field?(module, field) do
    type = module.__schema__(:type, field)
    UUIDSchema.uuid_type?(type)
  end

  defp invalid_generation?(module, key, adapter, generated, version) do
    adapter_generated = match?({^key, _source, _type}, adapter)
    generators = for {fields, mfa} <- generated, key in fields, do: mfa

    uuid_field?(module, key) and
      (adapter_generated or Enum.any?(generators, &(not uuid_generator?(&1, version))))
  end

  defp uuid_generator?({Ecto.UUID, function, [opts]}, version)
       when function in [:autogenerate, :generate] and is_list(opts),
       do: Keyword.get(opts, :version, 4) == version

  defp uuid_generator?({Ecto.UUID, function, []}, 4) when function in [:autogenerate, :generate],
    do: true

  defp uuid_generator?(_generator, _version), do: false

  defp issue(module, file, line, reason, fields, message) do
    %{
      module: module,
      file: file,
      line: line,
      reason: reason,
      missing_fields: fields,
      message: message
    }
  end
end
